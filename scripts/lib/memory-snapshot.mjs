import fs from "node:fs/promises";
import path from "node:path";

import { listBacklog, filterBacklog } from "./backlog-parser.mjs";
import { listSpecs } from "./spec-parser.mjs";
import { listGrades, SCORE_DIMENSIONS } from "./grade-parser.mjs";
import { listDecisions } from "./decisions-store.mjs";

// Writes a single durable snapshot of autonomous-loop state to
// docs/autonomous-loop-snapshot.md. Designed to be `@`-referenced from
// CLAUDE.md or read by crew brief-me as cross-session memory. Regenerate
// after material state changes (slice complete, release cut, spec
// satisfied). Pure aggregation — no LLM.

function avg(values) {
  const nums = values.filter((v) => typeof v === "number");
  if (nums.length === 0) return null;
  return Number((nums.reduce((a, b) => a + b, 0) / nums.length).toFixed(3));
}

export async function writeMemorySnapshot(repoPath, { config = null } = {}) {
  const [backlog, specs, grades, decisions] = await Promise.all([
    listBacklog(repoPath, { config }),
    listSpecs(repoPath, { config }),
    listGrades(repoPath, { config }),
    listDecisions(repoPath, { config })
  ]);

  const today = new Date().toISOString().slice(0, 10);
  const inFlight = filterBacklog(backlog, { status: "in-progress" });
  const triagedTop = filterBacklog(backlog, { status: "triaged" })
    .sort((a, b) => (a.frontmatter.priority || "P3").localeCompare(b.frontmatter.priority || "P3"))
    .slice(0, 5);
  const specsByStatus = {
    draft: specs.filter((s) => s.frontmatter.status === "draft").length,
    approved: specs.filter((s) => s.frontmatter.status === "approved").length,
    decomposed: specs.filter((s) => s.frontmatter.status === "decomposed").length,
    satisfied: specs.filter((s) => s.frontmatter.status === "satisfied").length
  };
  const recentGrades = grades.slice(-5);
  const recentScoreAverages = {};
  for (const dim of SCORE_DIMENSIONS) {
    recentScoreAverages[dim] = avg(recentGrades.map((g) => g.scores?.[dim]));
  }
  const recentDecisions = decisions.slice(-5);

  const lines = [];
  lines.push(`# Autonomous Loop snapshot — ${today}`);
  lines.push("");
  lines.push(
    "_Generated by `/autonomous-loop:snapshot-memory`. Regenerate after material state changes._"
  );
  lines.push("");
  lines.push("## Backlog state");
  lines.push("");
  lines.push(`- Pending: ${filterBacklog(backlog, { status: "pending" }).length}`);
  lines.push(`- Triaged: ${filterBacklog(backlog, { status: "triaged" }).length}`);
  lines.push(`- In-progress: ${inFlight.length}`);
  lines.push(`- Done: ${filterBacklog(backlog, { status: "done" }).length}`);
  lines.push("");
  if (inFlight.length > 0) {
    lines.push("## In-flight features");
    lines.push("");
    for (const f of inFlight) {
      lines.push(
        `- **${f.id}** (${f.frontmatter.priority || "?"}) — slices: ${(f.frontmatter.slices || []).join(", ") || "(none yet — orphan)"}`
      );
    }
    lines.push("");
  }
  if (triagedTop.length > 0) {
    lines.push("## Top triaged (next to slice)");
    lines.push("");
    for (const f of triagedTop) {
      lines.push(
        `- **${f.id}** (${f.frontmatter.priority}) ${f.frontmatter.category ? `[${f.frontmatter.category}]` : ""} → ${f.frontmatter.target_release || "(release tbd)"}`
      );
    }
    lines.push("");
  }
  lines.push("## Specs");
  lines.push("");
  lines.push(
    `- Total: ${specs.length} (draft: ${specsByStatus.draft}, approved: ${specsByStatus.approved}, decomposed: ${specsByStatus.decomposed}, satisfied: ${specsByStatus.satisfied})`
  );
  if (specs.filter((s) => s.frontmatter.status === "approved").length > 0) {
    lines.push("- ⚠ Approved + undecomposed specs need decomposition:");
    for (const s of specs.filter(
      (s) =>
        s.frontmatter.status === "approved" &&
        (!s.frontmatter.derived_features || s.frontmatter.derived_features.length === 0)
    )) {
      lines.push(`  - ${s.id} (${s.frontmatter.type}): ${s.frontmatter.title}`);
    }
  }
  lines.push("");
  lines.push("## Recent grade signal");
  lines.push("");
  lines.push(`- Total grades: ${grades.length}`);
  lines.push(`- Last 5 averages:`);
  for (const [dim, value] of Object.entries(recentScoreAverages)) {
    const flag = value !== null && value < 0.8 ? " ⚠" : "";
    lines.push(`  - ${dim}: ${value === null ? "n/a" : value}${flag}`);
  }
  lines.push("");
  lines.push("## Recent decisions");
  lines.push("");
  if (recentDecisions.length === 0) {
    lines.push("_(none yet)_");
  } else {
    for (const d of recentDecisions) {
      lines.push(
        `- **${d.id}** (${d.status}) — ${d.title} _(from ${d.introduced_by_slice || "n/a"})_`
      );
    }
  }
  lines.push("");
  lines.push("## How to use this file");
  lines.push("");
  lines.push(
    "- Reference from `CLAUDE.md` via `@docs/autonomous-loop-snapshot.md` so agents pick it up at session start."
  );
  lines.push(
    "- Regenerate via `/autonomous-loop:snapshot-memory` whenever the picture shifts materially."
  );
  lines.push("");

  const target = path.join(repoPath, "docs", "autonomous-loop-snapshot.md");
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, lines.join("\n"));
  return {
    artifactPath: target,
    counts: {
      backlog: backlog.length,
      specs: specs.length,
      grades: grades.length,
      decisions: decisions.length
    }
  };
}
